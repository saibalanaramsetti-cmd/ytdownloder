import os
from pathlib import Path
from typing import Optional
from pydantic import BaseModel

BASE_DIR = Path(__file__).resolve().parent.parent
STORAGE_DIR = Path(os.getenv("STORAGE_DIR", str(BASE_DIR / "temp_storage")))
STORAGE_DIR.mkdir(parents=True, exist_ok=True)

class Settings(BaseModel):
    APP_NAME: str = "MediaFlow API"
    APP_VERSION: str = "1.0.0"
    DEBUG: bool = os.getenv("DEBUG", "False").lower() in ("true", "1")
    HOST: str = os.getenv("HOST", "0.0.0.0")
    PORT: int = int(os.getenv("PORT", "8000"))
    
    # Database
    DATABASE_URL: str = os.getenv("DATABASE_URL", f"sqlite+aiosqlite:///{BASE_DIR}/mediaflow.db")
    
    # Redis
    REDIS_URL: str = os.getenv("REDIS_URL", "redis://localhost:6379/0")
    USE_REDIS_IF_AVAILABLE: bool = True
    
    # Security & Storage
    SECRET_KEY: str = os.getenv("SECRET_KEY", "mediaflow-secret-production-token-2026-key-signature")
    DOWNLOAD_TTL_SECONDS: int = int(os.getenv("DOWNLOAD_TTL_SECONDS", "3600")) # 1 hour
    MAX_FILE_SIZE_BYTES: int = int(os.getenv("MAX_FILE_SIZE_BYTES", str(2 * 1024 * 1024 * 1024))) # 2 GB
    MAX_DURATION_SECONDS: int = int(os.getenv("MAX_DURATION_SECONDS", str(3 * 3600))) # 3 hours
    STORAGE_PATH: Path = STORAGE_DIR

    # Rate Limiting
    MAX_REQUESTS_PER_MINUTE: int = int(os.getenv("MAX_REQUESTS_PER_MINUTE", "60"))
    
    # Worker concurrency
    WORKER_CONCURRENCY: int = int(os.getenv("WORKER_CONCURRENCY", "4"))

settings = Settings()

def format_cookie_content(raw: str) -> str:
    text = raw.strip()
    if "\\n" in text:
        text = text.replace("\\n", "\n")
    if "\\t" in text:
        text = text.replace("\\t", "\t")
    
    lines = []
    has_header = False
    for line in text.splitlines():
        line_str = line.strip()
        if not line_str:
            continue
        if line_str.startswith("# Netscape"):
            has_header = True
            lines.append(line_str)
            continue
        if line_str.startswith("#"):
            lines.append(line_str)
            continue
        if "\t" in line_str:
            lines.append(line_str)
        else:
            parts = line_str.split()
            if len(parts) >= 7:
                domain, flag, path, secure, exp, name = parts[:6]
                val = " ".join(parts[6:])
                lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{exp}\t{name}\t{val}")
            else:
                lines.append(line_str)
    
    res = "\n".join(lines)
    if not has_header:
        res = "# Netscape HTTP Cookie File\n# Generated by MediaFlow\n" + res
    return res + "\n"

def get_cookie_file_path() -> Optional[str]:
    cookie_file_env = os.getenv("YOUTUBE_COOKIES_FILE")
    if cookie_file_env and os.path.exists(cookie_file_env):
        return cookie_file_env
    
    raw_cookies = (
        os.getenv("YOUTUBE_COOKIES") or 
        os.getenv("YOUTUBE_COOKIE") or 
        os.getenv("COOKIES") or 
        os.getenv("COOKIE")
    )
    if raw_cookies and len(raw_cookies.strip()) > 10:
        formatted = format_cookie_content(raw_cookies)
        cookie_path = settings.STORAGE_PATH / "youtube_cookies.txt"
        cookie_path.write_text(formatted, encoding="utf-8")
        return str(cookie_path)
    return None
